package cz.incad.kramerius.statistics;

/**
 * How an image stream was accessed; stored in the access log as the field image_kind.
 * Tiles of the zoomify and deepzoom viewers and thumbnails are not logged and have no kind.
 * The IIIF presentation manifest (/iiif-presentation/{pid}/manifest) is not logged on
 * purpose: it is a description of the document, the reads it leads to are logged on
 * their own (info.json, regions).
 */
public enum ImageAccessKind {
    /** whole stream from IMG_FULL (image, pdf, epub, ...) */
    FULL,
    PREVIEW,
    /** IIIF image info.json, the "page displayed" event of the viewers */
    IIIF_INFO,
    /** IIIF image region/size request that is not a viewer tile (crop, whole image, external client) */
    IIIF_REGION,
    /** viewer tile; written only when statistics.image.log_tiles is on */
    IIIF_TILE,
    /** one page rendered into a pdf generated by the core (pdf/selection, pdf/part, pdf/parent); one record per page */
    PDF_PAGE,
    /** whole document requested as a pdf (items/{pid}/requests/generate_pdf); one record per request */
    PDF_DOCUMENT,
    ZOOMIFY_DESCRIPTOR,
    DEEPZOOM_DESCRIPTOR
}
